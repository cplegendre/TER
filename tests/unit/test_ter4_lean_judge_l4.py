# --- unnecessary_handoff: forks, saved findings, orchestration (TER-DET-008)


BRIEF = "Find breaking changes in requests changelog"


@pytest.mark.req("TER-DET-008")
class TestUnnecessaryHandoffJudgeL4:
    def test_a_forked_subagent_doing_its_task_after_its_prompt_is_fine(
        self,
    ) -> None:
        # A forked transcript inherits the parent's handoff, then the fork's
        # own prompt, then the fork does the task.
        s = Script()
        s.task("Research requests changelog", BRIEF)
        s.prompt("You are the forked agent: " + BRIEF)
        s.bash("curl https://x.invalid/requests/changelog breaking changes", "...")
        assert found(s, "unnecessary_handoff") == []

    def test_saving_what_the_subagent_found_is_fine(self) -> None:
        s = Script()
        s.task("Research requests changelog", BRIEF, "Breaking: Session.mount")
        s.write("notes/requests-breaking-changes.md", "requests changelog breaking")
        assert found(s, "unnecessary_handoff") == []

    def test_orchestration_calls_are_fine(self) -> None:
        s = Script()
        s.task("Research requests changelog", BRIEF, "Async agent launched")
        s.call(
            "TaskOutput",
            ToolKind.OTHER,
            {"description": "requests changelog breaking changes"},
            "running",
        )
        assert found(s, "unnecessary_handoff") == []

    def test_boundary_redoing_it_before_any_prompt_is_uncertain_waste(
        self,
    ) -> None:
        s = Script()
        s.task("Research requests changelog", BRIEF)
        s.bash("curl https://x.invalid/requests/changelog breaking changes", "...")
        [f] = found(s, "unnecessary_handoff")
        assert f.uncertain and f.confidence <= 0.65


