"""Detector fixes from the second judged sample (judge-l4, 12 Oct 2026).

87 confident findings over 286 real sessions were judged by hand: 6 waste,
53 not waste, 28 unsure. Each class of false positive gets a positive,
negative and boundary case here; the four detectors promoted on 10 Oct
(unused_context, unused_traversal, unnecessary_handoff, excessive_context)
are uncertain again, counted as waste until verified (ADR 0006).
"""

from __future__ import annotations

import pytest
from ter4_lean_builder import PASS, Script

from ter.adapters.driven.tokenizers import RegexTokenizer
from ter.domain import ToolKind
from ter.domain.lean import Finding, LeanAnalysis, explain
from ter.domain.lean.facts import (
    harness_output_path,
    injected_prompt,
    looks_like_file_name,
    runs_check,
    shell_intent,
)
from ter.domain.lean.model import ShellIntent


def run(script: Script) -> LeanAnalysis:
    return explain(script.events, RegexTokenizer())


def found(script: Script, detector: str) -> list[Finding]:
    return [f for f in run(script).findings if f.detector == detector]


# --- injected harness messages state no intent (TER-ITN-008) ---------------


@pytest.mark.req("TER-ITN-008")
@pytest.mark.parametrize(
    "text",
    [
        "<task-notification><task-id>a1</task-id><status>completed</status>",
        "<command-name>/model</command-name>\n<command-args>opus</command-args>",
        "<local-command-stdout>Set model to opus</local-command-stdout>",
        "[Request interrupted by user]",
        "[Request interrupted by user for tool use]",
        "Caveat: The messages below were generated by the user while running "
        "local commands. DO NOT respond to these messages.",
    ],
)
def test_harness_messages_are_injected(text: str) -> None:
    assert injected_prompt(text)


@pytest.mark.parametrize(
    "text",
    [
        "Add a slugify helper",
        "Why did the <task-notification> arrive twice?",
        "Please stop: [Request interrupted by user] keeps showing up",
    ],
)
def test_boundary_developer_text_mentioning_markers_is_not_injected(
    text: str,
) -> None:
    assert not injected_prompt(text)


@pytest.mark.req("TER-ITN-008")
def test_an_injected_message_is_not_an_intent_revision() -> None:
    s = Script()
    first = s.prompt("Add a slugify helper to src/text.py")
    s.prompt("<task-notification><task-id>a1</task-id> research done")
    s.prompt("[Request interrupted by user]")
    s.edit("src/text.py", "", "def slugify(text): ...")
    record = run(s).intent.record
    assert [r.event_id for r in record.revisions] == [first.id]


